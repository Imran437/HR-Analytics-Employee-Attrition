5. Entry-level employees and Sales Representatives have the highest attrition rates.

6. Younger employees (under 30 years old) and employees who live farther from
   the workplace are more likely to leave.

==========================================
          RECOMMENDATIONS
==========================================

1. Review compensation packages, salary hikes, and employee benefits.

2. Reduce overtime and improve work-life balance.

3. Conduct employee satisfaction surveys and improve workplace conditions.

4. Provide clear career growth opportunities and regular promotions.

5. Offer mentoring and training programs for entry-level employees.

6. Consider flexible work arrangements and transportation support for employees
   who live far from the workplace.
